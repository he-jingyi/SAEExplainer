def _to_int_from_response(text: str) -> int:
    try:
        return int(re.search(r"\d+", text).group())
    except Exception as exc:  # noqa: BLE001
        raise ValueError(f"Could not extract integer choice from judge response: {text!r}") from exc


def _build_valid_token_mask(
    input_ids_BL: torch.Tensor,
    attention_mask_BL: torch.Tensor,
    special_ids: set[int],
) -> torch.Tensor:
    valid_mask_BL = attention_mask_BL.bool().clone()
    if not special_ids:
        return valid_mask_BL
    special_mask_BL = torch.zeros_like(input_ids_BL, dtype=torch.bool)
    for token_id in special_ids:
        special_mask_BL |= input_ids_BL == token_id
    valid_mask_BL &= ~special_mask_BL
    return valid_mask_BL


def _sequence_kl_from_logits(
    clean_logits_BLV: torch.Tensor,
    hooked_logits_BLV: torch.Tensor,
    attention_mask_BL: torch.Tensor,
) -> float:
    clean_probs = F.softmax(clean_logits_BLV, dim=-1)
    hooked_probs = F.softmax(hooked_logits_BLV, dim=-1)
    token_kl = torch.sum(
        clean_probs * (torch.log(clean_probs.clamp_min(1e-10)) - torch.log(hooked_probs.clamp_min(1e-10))),
        dim=-1,
    )
    token_kl = token_kl * attention_mask_BL
    per_row: list[float] = []
    for row, mask in zip(token_kl, attention_mask_BL):
        valid = row[mask.bool()]
        if valid.numel() > 0:
            per_row.append(float(valid.mean().item()))
    return float(np.mean(per_row)) if per_row else 0.0


@dataclass
class InputMetricResult:
    pos_act_all: float
    neg_act_all: float
    pos_act_toks: float
    neg_act_toks: float
    positive_examples: list[str]
    negative_examples: list[str]

    def success(self) -> bool:
        return self.pos_act_toks > self.neg_act_toks


