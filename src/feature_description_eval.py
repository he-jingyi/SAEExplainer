def _load_existing_results(path: Path | None) -> tuple[list[dict[str, Any]], set[str]]:
    if path is None or not path.exists():
        return [], set()
    rows = load_jsonl(path)
    feature_ids = {
        str(row.get("feature_id") or "").strip()
        for row in rows
        if str(row.get("feature_id") or "").strip()
    }
    return rows, feature_ids


def _write_progress_snapshot(progress_json: Path | None, payload: dict[str, Any]) -> None:
    if progress_json is None:
        return
    progress_json.parent.mkdir(parents=True, exist_ok=True)
    progress_json.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def _resolve_target_scoring_model_name(
    records: list[dict[str, Any]],
    *,
    fallback_model_name: str,
) -> str:
    resolved_names = {
        resolve_record_target_base_model_name(
            record,
            fallback_model_name=fallback_model_name,
        )
        for record in records
    }
    if not resolved_names:
        return fallback_model_name
    if len(resolved_names) > 1:
        raise ValueError(
            "Expected a single target base model for feature-description evaluation, but found: "
            + ", ".join(sorted(resolved_names))
        )
    return next(iter(resolved_names))


def _normalize_generated_samples(raw_text: str) -> list[str]:
    raw_text = raw_text.strip()
    if not raw_text:
        return []
    try:
        payload = json.loads(raw_text)
        samples = payload.get("samples") or []
        cleaned = [str(item).strip() for item in samples if str(item).strip()]
        if cleaned:
            return cleaned
    except Exception:
        pass
    return [raw_text]


