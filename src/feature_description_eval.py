def _parse_pos_neg_json(raw_text: str) -> tuple[list[str], list[str]]:
    candidates = [
        raw_text.strip(),
        raw_text.strip().strip("json").strip("`").removeprefix("json\n").removesuffix("\n").strip(),
    ]
    for candidate in candidates:
        try:
            payload = json.loads(candidate)
            pos = [str(x).strip() for x in payload.get("positive") or [] if str(x).strip()]
            neg = [str(x).strip() for x in payload.get("negative") or [] if str(x).strip()]
            return pos, neg
        except Exception:
            pass
    raise ValueError("Could not parse positive/negative JSON lists from model response.")


