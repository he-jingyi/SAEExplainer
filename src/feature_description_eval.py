class DPOCheckpointExplanationProvider:
    def __init__(
        self,
        *,
        sft_config_path: Path,
        checkpoint_dir: Path,
        input_jsonl: Path,
        project_root: Path,
        device: torch.device,
        max_new_tokens: int | None = None,
        explanation_batch_size: int = 8,
    ) -> None:
        self.sft_cfg, self.tokenizer, self.model = load_checkpoint_model_for_eval(
            config_path=sft_config_path,
            checkpoint_dir=checkpoint_dir,
            project_root=project_root,
            device=device,
        )
        _, self.records, self.dataset = self._build_eval_dataset(
            config_path=sft_config_path,
            input_jsonl=input_jsonl,
            project_root=project_root,
            tokenizer=self.tokenizer,
        )
        self.device = device
        self.max_new_tokens = max_new_tokens or int(self.sft_cfg.eval.max_new_tokens)
        self.explanation_batch_size = max(1, int(explanation_batch_size))
        self.source_name = f"dpo_checkpoint:{checkpoint_dir.name}"
        self._explanation_cache: dict[int, str] = {}

    @staticmethod
    def _build_eval_dataset(
        *,
        config_path: Path,
        input_jsonl: Path,
        project_root: Path,
        tokenizer: Any,
    ) -> tuple[Any, list[dict[str, Any]], SAEExplainerSFTDataset]:
        sft_cfg = load_sft_config(config_path, project_root)
        records = load_jsonl(input_jsonl)
        data_cfg = replace(
            sft_cfg.data,
            train_jsonl=input_jsonl,
            val_ratio=0.0,
        )
        dataset = SAEExplainerSFTDataset(
            records=records,
            tokenizer=tokenizer,
            data_config=data_cfg,
            injection_config=sft_cfg.injection,
            project_root=project_root,
        )
        return sft_cfg, records, dataset

    @torch.no_grad()
    def get_explanation(self, *, record: dict[str, Any], dataset_index: int) -> str:
        cached = self._explanation_cache.get(dataset_index)
        if cached is not None:
            return cached
        if self.model is None:
            raise RuntimeError(
                "DPOCheckpointExplanationProvider model was released before explanation "
                f"for dataset_index={dataset_index} was materialized."
            )
        sample = self.dataset.build_eval_sample(dataset_index)
        input_ids = torch.tensor([sample["prompt_input_ids"]], dtype=torch.long, device=self.device)
        attention_mask = torch.ones_like(input_ids, dtype=torch.long, device=self.device)
        feature_vectors = torch.tensor(sample["feature_vector"][None, :], dtype=torch.float32, device=self.device)
        act_positions = torch.tensor([sample["act_position"]], dtype=torch.long, device=self.device)
        inject_mask = torch.tensor([sample["inject_mask"]], dtype=torch.bool, device=self.device)
        generated = self.model.generate_with_injection(
            input_ids=input_ids,
            attention_mask=attention_mask,
            feature_vectors=feature_vectors,
            act_positions=act_positions,
            inject_mask=inject_mask,
            max_new_tokens=self.max_new_tokens,
            do_sample=False,
            pad_token_id=self.tokenizer.pad_token_id,
            eos_token_id=self.tokenizer.eos_token_id,
        )
        completion_ids = generated[0, input_ids.shape[1] :]
        explanation = self.tokenizer.decode(completion_ids, skip_special_tokens=True).strip()
        self._explanation_cache[dataset_index] = explanation
        return explanation

    def materialize_explanations(self, dataset_indices: list[int]) -> None:
        pending_indices = [dataset_index for dataset_index in dataset_indices if dataset_index not in self._explanation_cache]
        iterator = tqdm(
            total=len(pending_indices),
            desc="Materializing DPO explanations",
            dynamic_ncols=True,
            unit="feature",
        )
        try:
            if self.model is None:
                raise RuntimeError("DPO checkpoint explainer model was already released before materialization.")
            for start in range(0, len(pending_indices), self.explanation_batch_size):
                batch_indices = pending_indices[start : start + self.explanation_batch_size]
                batch_samples = [self.dataset.build_eval_sample(dataset_index) for dataset_index in batch_indices]
                explanations = _generate_explanations_batch(
                    model=self.model,
                    tokenizer=self.tokenizer,
                    samples=batch_samples,
                    max_new_tokens=self.max_new_tokens,
                    device=self.device,
                )
                for dataset_index, explanation in zip(batch_indices, explanations, strict=True):
                    self._explanation_cache[dataset_index] = explanation
                iterator.update(len(batch_indices))
        finally:
            iterator.close()
            self.close()

    def close(self) -> None:
        if self.model is not None:
            del self.model
            self.model = None
            if self.device.type == "cuda":
                torch.cuda.empty_cache()


class LocalFeatureActivationScorer:
    def __init__(
        self,
        *,
        model_name: str,
        trust_remote_code: bool,
        torch_dtype: str,
        attn_implementation: str | None,
        max_length: int,
        sae_cache_dir: Path,
        device: torch.device,
    ) -> None:
        self.device = device
        self.max_length = max_length
        self.tokenizer = AutoTokenizer.from_pretrained(
            model_name,
            trust_remote_code=trust_remote_code,
        )
        if self.tokenizer.pad_token is None:
            self.tokenizer.pad_token = self.tokenizer.eos_token
        self.tokenizer.padding_side = "right"

        kwargs: dict[str, Any] = {
            "pretrained_model_name_or_path": model_name,
            "trust_remote_code": trust_remote_code,
            "torch_dtype": resolve_torch_dtype(torch_dtype),
        }
        if attn_implementation:
            kwargs["attn_implementation"] = attn_implementation

        self.model = AutoModelForCausalLM.from_pretrained(**kwargs).to(self.device).eval()
        self.special_ids = set(getattr(self.tokenizer, "all_special_ids", []) or [])
        self.sae_store = JumpReluSAEStore(local_dir=sae_cache_dir)

    def close(self) -> None:
        del self.model
        if self.device.type == "cuda":
            torch.cuda.empty_cache()

    @torch.no_grad()
    def score_text(self, *, text: str, record: dict[str, Any]) -> dict[str, Any]:
        locator = locator_from_record(record)
        metadata = record.get("metadata") or {}
        raw_hook_layer = metadata.get("hook_layer")
        hook_layer = int(raw_hook_layer if raw_hook_layer is not None else metadata.get("layer", 0))

        encoded = self.tokenizer(
            [text],
            return_tensors="pt",
            padding=True,
            truncation=True,
            max_length=self.max_length,
            return_attention_mask=True,
        )
        encoded = {key: value.to(self.device) for key, value in encoded.items()}
        outputs = self.model(**encoded, output_hidden_states=True, use_cache=False)
        hidden_states_LD = outputs.hidden_states[hook_layer + 1][0, : int(encoded["attention_mask"][0].sum().item())]
        valid_mask_L = _build_valid_token_mask(
            input_ids_BL=encoded["input_ids"],
            attention_mask_BL=encoded["attention_mask"],
            special_ids=self.special_ids,
        )[0, : hidden_states_LD.shape[0]]
        feature_score = self.sae_store.score_feature(
            hidden_states_LD=hidden_states_LD,
            locator=locator,
            valid_token_mask_L=valid_mask_L,
        )
        del outputs, encoded
        return {
            "max_activation": float(feature_score.max_activation),
            "mean_activation": float(feature_score.mean_activation),
            "sum_activation": float(feature_score.sum_activation),
        }

    @torch.no_grad()
    def score_texts_batch(self, *, texts: list[str], record: dict[str, Any]) -> list[dict[str, Any]]:
        if not texts:
            return []

        locator = locator_from_record(record)
        metadata = record.get("metadata") or {}
        raw_hook_layer = metadata.get("hook_layer")
        hook_layer = int(raw_hook_layer if raw_hook_layer is not None else metadata.get("layer", 0))

        encoded = self.tokenizer(
            texts,
            return_tensors="pt",
            padding=True,
            truncation=True,
            max_length=self.max_length,
            return_attention_mask=True,
        )
        encoded = {key: value.to(self.device) for key, value in encoded.items()}
        outputs = self.model(**encoded, output_hidden_states=True, use_cache=False)
        hidden_states_BLD = outputs.hidden_states[hook_layer + 1]
        valid_mask_BL = _build_valid_token_mask(
            input_ids_BL=encoded["input_ids"],
            attention_mask_BL=encoded["attention_mask"],
            special_ids=self.special_ids,
        )

        results: list[dict[str, Any]] = []
        batch_size = encoded["input_ids"].shape[0]
        for batch_index in range(batch_size):
            sequence_length = int(encoded["attention_mask"][batch_index].sum().item())
            hidden_states_LD = hidden_states_BLD[batch_index, :sequence_length]
            valid_mask_L = valid_mask_BL[batch_index, :sequence_length]
            feature_score = self.sae_store.score_feature(
                hidden_states_LD=hidden_states_LD,
                locator=locator,
                valid_token_mask_L=valid_mask_L,
            )
            results.append(
                {
                    "max_activation": float(feature_score.max_activation),
                    "mean_activation": float(feature_score.mean_activation),
                    "sum_activation": float(feature_score.sum_activation),
                }
            )

        del outputs, encoded
        return results


class TargetFeatureSteerer:
    def __init__(
        self,
        *,
        model_name: str,
        trust_remote_code: bool,
        torch_dtype: str,
        attn_implementation: str | None,
        max_length: int,
        sae_cache_dir: Path,
        device: torch.device,
        shared_model: Any | None = None,
    ) -> None:
        self.device = device
        self.max_length = max_length
        self.tokenizer = AutoTokenizer.from_pretrained(
            model_name,
            trust_remote_code=trust_remote_code,
        )
        if self.tokenizer.pad_token is None:
            self.tokenizer.pad_token = self.tokenizer.eos_token
        # Decoder-only batch generation should use left padding so prompts align
        # at the sequence end during generation.
        self.tokenizer.padding_side = "left"
        self._owns_model = shared_model is None
        if shared_model is None:
            kwargs: dict[str, Any] = {
                "pretrained_model_name_or_path": model_name,
                "trust_remote_code": trust_remote_code,
                "torch_dtype": resolve_torch_dtype(torch_dtype),
            }
            if attn_implementation:
                kwargs["attn_implementation"] = attn_implementation
            self.model = AutoModelForCausalLM.from_pretrained(**kwargs).to(device).eval()
        else:
            self.model = shared_model
        self.sae_scorer = JumpReluSAEStore(local_dir=sae_cache_dir)
        self.decoder_store = SAEVectorStore(local_dir=sae_cache_dir)
        self._sae_param_cache: dict[
            tuple[str, str, str, str],
            tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor],
        ] = {}

    def _try_get_saelens_sae(self, record: dict[str, Any]) -> Any | None:
        locator = locator_from_record(record)
        if not self.sae_scorer._should_try_saelens(locator):  # noqa: SLF001
            return None
        return self.sae_scorer._load_saelens_sae(locator, device=self.device)  # noqa: SLF001

    def close(self) -> None:
        if self._owns_model:
            del self.model
            if self.device.type == "cuda":
                torch.cuda.empty_cache()

    def _get_sae_torch_params(
        self,
        record: dict[str, Any],
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
        metadata = record.get("metadata") or {}
        locator = locator_from_record(record)
        dtype = next(self.model.parameters()).dtype
        cache_key = (
            locator.hf_repo_id,
            locator.hf_folder_id,
            str(self.device),
            str(dtype),
        )
        cached = self._sae_param_cache.get(cache_key)
        if cached is not None:
            return cached

        w_enc, b_enc, b_dec, threshold = self.sae_scorer._load_full_sae_params(locator)  # noqa: SLF001
        w_dec = self.decoder_store._load_decoder_matrix(locator)  # noqa: SLF001

        w_enc_DF = torch.from_numpy(w_enc).to(self.device, dtype=dtype)
        b_enc_F = torch.from_numpy(b_enc).to(self.device, dtype=dtype)
        b_dec_D = torch.from_numpy(b_dec).to(self.device, dtype=dtype)
        threshold_F = torch.from_numpy(threshold).to(self.device, dtype=dtype)
        w_dec_FD = torch.from_numpy(w_dec).to(self.device, dtype=dtype)

        params = (w_enc_DF, b_enc_F, b_dec_D, threshold_F, w_dec_FD)
        self._sae_param_cache[cache_key] = params
        return params

    def _hook_for_record(self, record: dict[str, Any], amplitude: float):
        metadata = record.get("metadata") or {}
        hook_layer = int(metadata.get("hook_layer", metadata.get("layer", 0)))
        target_feature = int(metadata.get("feature_index"))
        saelens_sae = self._try_get_saelens_sae(record)
        if saelens_sae is None:
            w_enc_DF, b_enc_F, b_dec_D, threshold_F, w_dec_FD = self._get_sae_torch_params(record)
        else:
            w_enc_DF = b_enc_F = b_dec_D = threshold_F = w_dec_FD = None
        module = resolve_injection_submodule(self.model, hook_layer)

        def hook_fn(_module, _inputs, output):
            if isinstance(output, tuple):
                resid_BLD, *rest = output
                out_is_tuple = True
            else:
                resid_BLD = output
                rest = []
                out_is_tuple = False

            target_dtype = resid_BLD.dtype

            if saelens_sae is not None:
                acts_BLF = saelens_sae.encode(resid_BLD)
                dirty_BLD = saelens_sae.decode(acts_BLF)
                error_term_BLD = resid_BLD - dirty_BLD
                steered_acts_BLF = acts_BLF.clone()
                steered_acts_BLF[:, :, target_feature] = amplitude
                steered_BLD = saelens_sae.decode(steered_acts_BLF)
                steered = (steered_BLD + error_term_BLD).to(dtype=target_dtype)
            else:
                assert w_enc_DF is not None
                assert b_enc_F is not None
                assert b_dec_D is not None
                assert threshold_F is not None
                assert w_dec_FD is not None

                centered_BLD = resid_BLD - b_dec_D.view(1, 1, -1)
                pre_acts_BLF = torch.einsum("bld,df->blf", centered_BLD, w_enc_DF) + b_enc_F.view(1, 1, -1)
                acts_BLF = torch.relu(pre_acts_BLF) * (pre_acts_BLF > threshold_F.view(1, 1, -1))
                dirty_BLD = torch.einsum("blf,fd->bld", acts_BLF, w_dec_FD) + b_dec_D.view(1, 1, -1)
                error_term_BLD = resid_BLD - dirty_BLD

                steered_acts_BLF = acts_BLF.clone()
                steered_acts_BLF[:, :, target_feature] = amplitude
                steered_BLD = torch.einsum("blf,fd->bld", steered_acts_BLF, w_dec_FD) + b_dec_D.view(1, 1, -1)
                steered = (steered_BLD + error_term_BLD).to(dtype=target_dtype)

            if out_is_tuple:
                return (steered, *rest)
            return steered

        return module.register_forward_hook(hook_fn)

    @torch.no_grad()
    def get_kl_divergence(self, prompts: list[str], record: dict[str, Any], amplitude: float) -> float:
        encoded = self.tokenizer(
            prompts,
            return_tensors="pt",
            padding=True,
            truncation=True,
            max_length=self.max_length,
            return_attention_mask=True,
        )
        encoded = {key: value.to(self.device) for key, value in encoded.items()}
        clean_logits = self.model(**encoded, use_cache=False).logits
        handle = self._hook_for_record(record, amplitude)
        try:
            hooked_logits = self.model(**encoded, use_cache=False).logits
        finally:
            handle.remove()
        return _sequence_kl_from_logits(clean_logits, hooked_logits, encoded["attention_mask"])

    @torch.no_grad()
    def find_amplitude_for_target_kl(
        self,
        prompts: list[str],
        record: dict[str, Any],
        target_kl: float,
        *,
        high_thresh: float = 0.1,
        max_abs_amplitude: float = 1000.0,
    ) -> float:
        negative = target_kl < 0
        target = abs(float(target_kl))
        low, high = ((-max_abs_amplitude, -1.0) if negative else (1.0, max_abs_amplitude))
        mid = 0.0
        current_kl = -1.0
        while (low + 1 < high) and (current_kl < target or current_kl > target + high_thresh):
            mid = math.floor((low + high) / 2.0)
            current_kl = self.get_kl_divergence(prompts, record, mid)
            if (negative and current_kl < target) or ((not negative) and current_kl > target):
                high = mid
            else:
                low = mid
        return mid

    @torch.no_grad()
    def generate_steered_completions(
        self,
        *,
        prompts: list[str],
        record: dict[str, Any],
        amplitude: float,
        max_new_tokens: int,
        temperature: float,
    ) -> list[str]:
        encoded = self.tokenizer(
            prompts,
            return_tensors="pt",
            padding=True,
            truncation=True,
            max_length=self.max_length,
            return_attention_mask=True,
        )
        encoded = {key: value.to(self.device) for key, value in encoded.items()}
        handle = self._hook_for_record(record, amplitude)
        try:
            generated = self.model.generate(
                input_ids=encoded["input_ids"],
                attention_mask=encoded["attention_mask"],
                max_new_tokens=max_new_tokens,
                do_sample=True,
                temperature=temperature,
                top_p=0.95,
                pad_token_id=self.tokenizer.pad_token_id,
                eos_token_id=self.tokenizer.eos_token_id,
            )
        finally:
            handle.remove()
        prompt_length = encoded["input_ids"].shape[1]
        results: list[str] = []
        for row_index in range(generated.shape[0]):
            completion_ids = generated[row_index, prompt_length:]
            results.append(self.tokenizer.decode(completion_ids, skip_special_tokens=True).strip().replace("\n", "\\n").replace("\r", "\\r"))
        return results


def _format_amplification_bundle(kl_values: list[float], completions_by_kl: list[list[str]]) -> str:
    lines: list[str] = []
    for kl_value, completions in zip(kl_values, completions_by_kl):
        lines.append(f"<{kl_value:+g}>")
        for prompt, completion in zip(OUTPUT_METRIC_GENERATION_PROMPTS, completions):
            lines.append(f"'{prompt}': '{completion}'")
    return "\n".join(lines)


class FeatureDescriptionEvaluator:
    def __init__(
        self,
        *,
        sft_config_path: Path,
        input_jsonl: Path,
        project_root: Path,
        provider: ExplanationProvider,
        metric_client: Any,
        input_metric_llm_model: str,
        output_metric_judge_model: str,
        device: torch.device,
        max_features: int | None = None,
        sample_features: int | None = None,
        sample_seed: int = 42,
        steering_max_new_tokens: int = 25,
        steering_temperature: float = 0.75,
        kl_div_values: list[float] | None = None,
        num_distractor_bundles: int = DEFAULT_NUM_DISTRACTOR_BUNDLES,
        random_bundle_pool_size: int = 8,
        run_input_metric: bool = True,
        run_output_metric: bool = True,
    ) -> None:
        self.project_root = project_root
        self.provider = provider
        self.metric_client = metric_client
        self.input_metric_llm_model = input_metric_llm_model
        self.output_metric_judge_model = output_metric_judge_model
        self.device = device
        self.steering_max_new_tokens = steering_max_new_tokens
        self.steering_temperature = steering_temperature
        self.kl_div_values = kl_div_values or list(DEFAULT_KL_DIV_VALUES)
        self.num_distractor_bundles = num_distractor_bundles
        self.random_bundle_pool_size = random_bundle_pool_size
        self.run_input_metric = bool(run_input_metric)
        self.run_output_metric = bool(run_output_metric)

        if not self.run_input_metric and not self.run_output_metric:
            raise ValueError("At least one of run_input_metric / run_output_metric must be enabled.")

        self.sft_cfg = load_sft_config(sft_config_path, project_root)
        self.records = load_jsonl(input_jsonl)
        indices = list(range(len(self.records)))
        if max_features is not None:
            indices = indices[:max_features]
        if sample_features is not None:
            rng = random.Random(sample_seed)
            indices = rng.sample(indices, k=min(sample_features, len(indices)))
        self.active_indices = indices
        self.active_records = [self.records[index] for index in indices]
        self.target_scoring_model_name = _resolve_target_scoring_model_name(
            self.active_records,
            fallback_model_name=self.sft_cfg.model.model_name,
        )

        self.activation_scorer = LocalFeatureActivationScorer(
            model_name=self.target_scoring_model_name,
            trust_remote_code=self.sft_cfg.model.trust_remote_code,
            torch_dtype=self.sft_cfg.model.torch_dtype,
            attn_implementation=self.sft_cfg.model.attn_implementation,
            max_length=self.sft_cfg.data.max_length,
            sae_cache_dir=project_root / "data" / "cache" / "hf_saes",
            device=device,
        )
        self.steerer = TargetFeatureSteerer(
            model_name=self.target_scoring_model_name,
            trust_remote_code=self.sft_cfg.model.trust_remote_code,
            torch_dtype=self.sft_cfg.model.torch_dtype,
            attn_implementation=self.sft_cfg.model.attn_implementation,
            max_length=self.sft_cfg.data.max_length,
            sae_cache_dir=project_root / "data" / "cache" / "hf_saes",
            device=device,
            shared_model=self.activation_scorer.model,
        )
        self._random_bundle_pool: dict[tuple[str, str], list[str]] = {}

    def close(self) -> None:
        self.activation_scorer.close()
        self.steerer.close()
        if hasattr(self.provider, "close"):
            try:
                self.provider.close()  # type: ignore[attr-defined]
            except Exception:
                pass

    def _query_llm(self, *, model_name: str, messages: list[dict[str, str]], max_output_tokens: int = 2048) -> str:
        return _invoke_openai_messages(
            client=self.metric_client,
            messages=messages,
            model_name=model_name,
            max_output_tokens=max_output_tokens,
            temperature=0.1,
            top_p=1.0,
        )

    def _generate_pos_neg_lists(self, explanation: str) -> tuple[list[str], list[str]]:
        response = self._query_llm(
            model_name=self.input_metric_llm_model,
            messages=[{"role": "user", "content": GEN_LISTS_PROMPT.format(explanation=explanation)}],
            max_output_tokens=2048,
        )
        try:
            return _parse_pos_neg_json(response)
        except Exception as first_exc:
            fixed = self._query_llm(
                model_name=self.input_metric_llm_model,
                messages=[{"role": "user", "content": FIX_JSON_PROMPT.format(json=response)}],
                max_output_tokens=2048,
            )
            try:
                return _parse_pos_neg_json(fixed)
            except Exception as second_exc:
                explanation_preview = _truncate_debug_text(explanation, max_chars=300)
                raw_preview = _truncate_debug_text(response)
                fixed_preview = _truncate_debug_text(fixed)
                raise ValueError(
                    "Could not parse positive/negative JSON lists from model response.\n"
                    f"Explanation preview: {explanation_preview!r}\n"
                    f"First parse error: {first_exc}\n"
                    f"Raw model response: {raw_preview}\n"
                    f"Second parse error: {second_exc}\n"
                    f"Fixed model response: {fixed_preview}"
                ) from second_exc

    def evaluate_input_metric(self, explanation: str, record: dict[str, Any]) -> InputMetricResult:
        positive_examples, negative_examples = self._generate_pos_neg_lists(explanation)
        if not positive_examples or not negative_examples:
            return InputMetricResult(
                pos_act_all=0.0,
                neg_act_all=0.0,
                pos_act_toks=0.0,
                neg_act_toks=0.0,
                positive_examples=positive_examples,
                negative_examples=negative_examples,
            )
        pos_scores = self.activation_scorer.score_texts_batch(texts=positive_examples, record=record)
        neg_scores = self.activation_scorer.score_texts_batch(texts=negative_examples, record=record)
        return InputMetricResult(
            pos_act_all=max(score["max_activation"] for score in pos_scores) if pos_scores else 0.0,
            neg_act_all=max(score["max_activation"] for score in neg_scores) if neg_scores else 0.0,
            pos_act_toks=float(np.mean([score["max_activation"] for score in pos_scores])) if pos_scores else 0.0,
            neg_act_toks=float(np.mean([score["max_activation"] for score in neg_scores])) if neg_scores else 0.0,
            positive_examples=positive_examples,
            negative_examples=negative_examples,
        )

    def _get_bundle_for_record(self, record: dict[str, Any]) -> str:
        completions_by_kl: list[list[str]] = []
        prompts = list(OUTPUT_METRIC_GENERATION_PROMPTS)
        for kl_value in self.kl_div_values:
            amplitude = self.steerer.find_amplitude_for_target_kl(prompts, record, kl_value)
            completions = self.steerer.generate_steered_completions(
                prompts=prompts,
                record=record,
                amplitude=amplitude,
                max_new_tokens=self.steering_max_new_tokens,
                temperature=self.steering_temperature,
            )
            completions_by_kl.append(completions)
        return _format_amplification_bundle(self.kl_div_values, completions_by_kl)

    def _distractor_pool_key(self, record: dict[str, Any]) -> tuple[str, str]:
        metadata = record.get("metadata") or {}
        return (
            str(metadata.get("hf_repo_id") or metadata.get("target_model") or ""),
            str(metadata.get("hf_folder_id") or metadata.get("sae_id") or ""),
        )

    def _ensure_random_bundle_pool(self, record: dict[str, Any]) -> list[str]:
        key = self._distractor_pool_key(record)
        cached = self._random_bundle_pool.get(key)
        if cached is not None:
            return cached

        metadata = record.get("metadata") or {}
        d_sae = int(metadata.get("d_sae", 0) or 0)
        if d_sae <= 1:
            raise ValueError(f"Record {record.get('feature_id')} does not expose a valid d_sae for distractor sampling.")

        pool: list[str] = []
        rng = random.Random(42)
        for _ in range(self.random_bundle_pool_size):
            random_record = copy.deepcopy(record)
            random_feature = rng.randrange(d_sae)
            while random_feature == int(metadata.get("feature_index", -1)):
                random_feature = rng.randrange(d_sae)
            random_record.setdefault("metadata", {})["feature_index"] = random_feature
            pool.append(self._get_bundle_for_record(random_record))

        self._random_bundle_pool[key] = pool
        return pool

    def evaluate_output_metric(self, explanation: str, record: dict[str, Any]) -> OutputMetricResult:
        if self.num_distractor_bundles != 2:
            raise ValueError("Current prompt template expects exactly 2 distractor bundles and 1 target bundle.")
        target_bundle = self._get_bundle_for_record(record)
        distractor_pool = self._ensure_random_bundle_pool(record)
        distractors = random.sample(distractor_pool, k=min(self.num_distractor_bundles, len(distractor_pool)))
        bundles = distractors + [target_bundle]
        random_indices = list(range(len(bundles)))
        random.shuffle(random_indices)
        ordered_bundles = [bundles[index] for index in random_indices]
        correct_choice = random_indices.index(len(bundles) - 1) + 1

        prompt = STEERING_FULL_PROMPT_TEMPLATE.format(
            explanation=explanation,
            amplifications1=ordered_bundles[0],
            amplifications2=ordered_bundles[1],
            amplifications3=ordered_bundles[2],
        )
        judge_response = self._query_llm(
            model_name=self.output_metric_judge_model,
            messages=[{"role": "user", "content": OUTPUT_METRIC_SYS_PROMPT + "\n\n" + prompt}],
            max_output_tokens=1024,
        )
        chosen_index = _to_int_from_response(judge_response.splitlines()[-1] if judge_response.splitlines() else judge_response)
        return OutputMetricResult(
            correct_choice=correct_choice,
            chosen_index=chosen_index,
            judge_response=judge_response,
            ordered_bundles=ordered_bundles,
            target_bundle_index=correct_choice,
        )

    def evaluate_feature(self, *, record: dict[str, Any], dataset_index: int) -> FeatureDescriptionEvalResult | None:
        explanation = self.provider.get_explanation(record=record, dataset_index=dataset_index).strip()
        if not explanation:
            empty_input_metric = InputMetricResult(
                pos_act_all=0.0,
                neg_act_all=0.0,
                pos_act_toks=0.0,
                neg_act_toks=0.0,
                positive_examples=[],
                negative_examples=[],
            )
            empty_output_metric = OutputMetricResult(
                correct_choice=0,
                chosen_index=-1,
                judge_response="",
                ordered_bundles=[],
                target_bundle_index=0,
            )
            return FeatureDescriptionEvalResult(
                feature_id=str(record.get("feature_id") or ""),
                explanation="",
                source=self.provider.source_name,
                input_metric=empty_input_metric,
                output_metric=empty_output_metric,
                metadata=dict(record.get("metadata") or {}),
                missing_explanation=True,
            )
        input_metric = (
            self.evaluate_input_metric(explanation, record)
            if self.run_input_metric
            else InputMetricResult(
                pos_act_all=0.0,
                neg_act_all=0.0,
                pos_act_toks=0.0,
                neg_act_toks=0.0,
                positive_examples=[],
                negative_examples=[],
            )
        )
        output_metric = (
            self.evaluate_output_metric(explanation, record)
            if self.run_output_metric
            else OutputMetricResult(
                correct_choice=0,
                chosen_index=-1,
                judge_response="",
                ordered_bundles=[],
                target_bundle_index=0,
            )
        )
        return FeatureDescriptionEvalResult(
            feature_id=str(record.get("feature_id") or ""),
            explanation=explanation,
            source=self.provider.source_name,
            input_metric=input_metric,
            output_metric=output_metric,
            metadata=dict(record.get("metadata") or {}),
            missing_explanation=False,
        )

    def evaluate(
        self,
        *,
        output_jsonl: Path | None = None,
        output_summary: Path | None = None,
        progress_json: Path | None = None,
        overwrite: bool = False,
    ) -> dict[str, Any]:
        if overwrite and output_jsonl is not None and output_jsonl.exists():
            output_jsonl.unlink()
        if overwrite and output_summary is not None and output_summary.exists():
            output_summary.unlink()
        if overwrite and progress_json is not None and progress_json.exists():
            progress_json.unlink()

        existing_rows, completed_feature_ids = _load_existing_results(output_jsonl)
        results: list[FeatureDescriptionEvalResult] = []
        for row in existing_rows:
            try:
                results.append(
                    FeatureDescriptionEvalResult(
                        feature_id=str(row["feature_id"]),
                        explanation=str(row["explanation"]),
                        source=str(row["source"]),
                        input_metric=InputMetricResult(**row["input_metric"]),
                        output_metric=OutputMetricResult(**row["output_metric"]),
                        metadata=dict(row.get("metadata") or {}),
                        missing_explanation=bool(row.get("missing_explanation", False)),
                    )
                )
            except Exception:
                continue

        progress = tqdm(
            total=len(self.active_indices),
            desc="Evaluating feature descriptions",
            dynamic_ncols=True,
            unit="feature",
            initial=len(completed_feature_ids),
        )
        output_handle = None
        if output_jsonl is not None:
            output_jsonl.parent.mkdir(parents=True, exist_ok=True)
            output_handle = output_jsonl.open("a", encoding="utf-8")

        try:
            for dataset_index, record in zip(self.active_indices, self.active_records):
                feature_id = str(record.get("feature_id") or "").strip()
                if feature_id in completed_feature_ids:
                    continue
                progress.set_postfix(feature=feature_id.split("/")[-1])
                result = self.evaluate_feature(record=record, dataset_index=dataset_index)
                if result is not None:
                    results.append(result)
                    completed_feature_ids.add(result.feature_id)
                    if output_handle is not None:
                        output_handle.write(json.dumps(asdict(result), ensure_ascii=False) + "\n")
                        output_handle.flush()

                summary_payload = {
                    "num_features_total": len(self.active_indices),
                    "num_features_scored": len(results),
                    "num_features_completed": len(completed_feature_ids),
                    "source": self.provider.source_name,
                    "run_input_metric": self.run_input_metric,
                    "run_output_metric": self.run_output_metric,
                    "input_metric_success_rate": (
                        float(np.mean([item.input_metric.success() for item in results])) if results else 0.0
                    ),
                    "output_metric_success_rate": (
                        float(np.mean([item.output_metric.success() for item in results])) if results else 0.0
                    ),
                }
                _write_progress_snapshot(progress_json, summary_payload)
                progress.update(1)
        finally:
            if output_handle is not None:
                output_handle.close()
            progress.close()

        summary = {
            "num_features_total": len(self.active_indices),
            "num_features_scored": len(results),
            "num_features_completed": len(completed_feature_ids),
            "source": self.provider.source_name,
            "run_input_metric": self.run_input_metric,
            "run_output_metric": self.run_output_metric,
            "input_metric_success_rate": (
                float(np.mean([item.input_metric.success() for item in results])) if results else 0.0
            ),
            "output_metric_success_rate": (
                float(np.mean([item.output_metric.success() for item in results])) if results else 0.0
            ),
            "avg_pos_act_toks": (
                float(np.mean([item.input_metric.pos_act_toks for item in results])) if results else 0.0
            ),
            "avg_neg_act_toks": (
                float(np.mean([item.input_metric.neg_act_toks for item in results])) if results else 0.0
            ),
            "avg_pos_act_all": (
                float(np.mean([item.input_metric.pos_act_all for item in results])) if results else 0.0
            ),
            "avg_neg_act_all": (
                float(np.mean([item.input_metric.neg_act_all for item in results])) if results else 0.0
            ),
        }

        if output_summary is not None:
            output_summary.parent.mkdir(parents=True, exist_ok=True)
            output_summary.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
        _write_progress_snapshot(progress_json, summary)
        return summary
