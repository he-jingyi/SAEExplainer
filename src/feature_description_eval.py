"""Feature description evaluation with input/output metrics.

- Input metric: generate positive / negative texts from an explanation, then
  compare the target feature's activations on those texts.
- Output metric: steer the target feature, collect completions under several
  calibrated KL targets, and ask a judge model to identify the true steered set
  against random distractor bundles.

The evaluation pipeline is explanation-source agnostic: comparisons across
descriptions only need to swap the explanation provider while keeping the
metric logic unchanged.
"""

